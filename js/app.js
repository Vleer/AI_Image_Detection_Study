/* Flow controller: owns the study context and runs the screens in order. */
(function (global) {
  'use strict';

  var RAI = global.RAI = global.RAI || {};

  // Slices of the progress bar, so it advances smoothly across the session.
  var SPAN = {
    baseline: { base: 0.10, span: 0.25 },
    priming:  { base: 0.35, span: 0.40 },
    posttest: { base: 0.75, span: 0.17 }
  };

  /** Renders a screen module and resolves when it calls ctx.next(). */
  function show(screen, ctx) {
    return new Promise(function (resolve) {
      screen.render({
        next: resolve,
        session: ctx.session,
        rng: ctx.rng,
        allocator: ctx.allocator
      });
    });
  }

  function fatal(message, detail) {
    RAI.ui.setProgress(null);
    RAI.ui.render(
      '<div class="prose prose--narrow"><div class="card">' +
        '<div class="eyebrow" style="color:var(--danger)">Something went wrong</div>' +
        '<h2>' + RAI.ui.escapeHtml(message) + '</h2>' +
        (detail ? '<p class="muted">' + RAI.ui.escapeHtml(detail) + '</p>' : '') +
        '<p class="faint">Refreshing the page will start a new session.</p>' +
      '</div></div>'
    );
  }

  function bucketsNeeded() {
    var cfg = RAI.config;
    var blocks = cfg.forcedPrimingRatio !== null ? 1
      : (cfg.primingDesign === 'within' ? cfg.primingRatios.length : 1);
    return cfg.trials.baseline + cfg.trials.primingBlock * blocks + cfg.trials.posttest;
  }

  function init() {
    var cfg = RAI.config;
    var ui = RAI.ui;

    // Anything left over from a previous participant is archived, not lost.
    RAI.store.archivePrevious();
    var session = RAI.store.start(true);

    var rng = RAI.rng.make(session.seed);
    var pool;
    try {
      pool = RAI.stimuli.buildPool();
    } catch (err) {
      return fatal('The image set is not configured yet.', err.message);
    }

    var need = bucketsNeeded();
    if (cfg.uniqueBucketsAcrossStudy && pool.length < need) {
      console.warn('[recognizeAI] Need ' + need + ' buckets for a no-repeat session but only ' +
                   pool.length + ' are available; some scenes will repeat.');
    }

    var ctx = {
      session: session,
      rng: rng,
      allocator: new RAI.stimuli.Allocator(pool, rng)
    };

    session.condition.primingRatios = RAI.screens.priming.assignCondition(rng);
    session.condition.aiSourceOrder = rng.shuffle(cfg.aiSources);
    RAI.store.save();
    RAI.store.logEvent('session_start', {
      poolSize: pool.length,
      bucketsNeeded: need,
      ratios: session.condition.primingRatios
    });

    var S = RAI.screens;

    var baselineIntro = S.instructions.make({
      eyebrow: 'Phase 1',
      title: 'Phase 1',
      body:
        '<p>You will see <strong>' + cfg.trials.baseline + ' images</strong>, one at a time. For each one, ' +
        'say whether you think it is a real photograph or was generated by software.</p>' +
        '<p class="muted">Some are real and some are not. Answer on first impression &mdash; there is no ' +
        'time limit, but there is no benefit to staring at an image for a long time. You will not be told ' +
        'whether you were right.</p>',
      cta: 'Continue',
      progress: SPAN.baseline.base,
      step: 'Phase 1',
      footer: 'Step 3 of 5',
      showKeys: true
    });

    var posttestIntro = S.instructions.make({
      eyebrow: 'Phase 3',
      title: 'Phase 3 \u2013 you will no longer receive feedback',
      body:
        '<p>Last block: <strong>' + cfg.trials.posttest + ' more images</strong>, same task.</p>' +
        '<p class="muted">The feedback is switched off again, so you will not find out whether you were ' +
        'right. Keep answering on first impression.</p>',
      cta: 'Continue',
      progress: SPAN.posttest.base,
      step: 'Phase 3',
      footer: 'Step 5 of 5',
      showKeys: true
    });

    function runJudgement(phase, count, spanKey, step) {
      var trials = RAI.stimuli.buildTrials({
        allocator: ctx.allocator,
        count: count,
        aiRatio: 0.5,          // pre- and post-test are balanced by design
        phase: phase,
        rng: rng
      });
      RAI.store.logEvent(phase + '_start', { n: trials.length });
      return S.judgement.runBlock({
        trials: trials,
        showFeedback: false,
        question: 'Is this a real photograph or AI-generated?',
        step: step,
        progressBase: SPAN[spanKey].base,
        progressSpan: SPAN[spanKey].span
      });
    }

    Promise.resolve()
      .then(function () { return show(S.welcome, ctx); })
      .then(function () { return show(S.consent, ctx); })
      .then(function () { return show(S.demographics, ctx); })
      .then(function () { return show(baselineIntro, ctx); })
      .then(function () { return runJudgement('baseline', cfg.trials.baseline, 'baseline', 'Set 1'); })
      .then(function () { return S.priming.run(ctx, SPAN.priming); })
      .then(function () { return show(posttestIntro, ctx); })
      .then(function () { return runJudgement('posttest', cfg.trials.posttest, 'posttest', 'Set 3'); })
      .then(function () {
        ctx.session.notes.stimulusReuse = ctx.allocator.reuseCount;
        RAI.store.save();
        return RAI.store.finish();
      })
      .then(function () { return show(S.debrief, ctx); })
      .catch(function (err) {
        console.error(err);
        RAI.ui.hideFlash();
        fatal('The study could not continue.', err && err.message);
      });
  }

  // Warn before an accidental refresh mid-session.
  global.addEventListener('beforeunload', function (e) {
    var s = RAI.store.get();
    if (s && s.trials.length && !s.completedAt) {
      e.preventDefault();
      e.returnValue = '';
    }
  });

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})(window);
