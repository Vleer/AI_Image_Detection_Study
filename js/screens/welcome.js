/* P1 — Welcome and consent.

   The cover story is deliberately vague about the real question (whether the
   feedback phase shifts how readily people call an image AI-generated). It
   describes the task honestly but frames the study as norm-collection on
   image judgement. Participants get the full explanation in the debrief. */
(function (global) {
  'use strict';

  var RAI = global.RAI = global.RAI || {};
  RAI.screens = RAI.screens || {};

  RAI.screens.welcome = {
    render: function (ctx) {
      var ui = RAI.ui;
      ui.setProgress(null);
      ui.setFooter('Anonymous \u00b7 you can stop at any time');

      ui.render(
        '<div class="prose">' +
          '<div class="card">' +
            '<div class="eyebrow">Research study</div>' +
            '<h1>How do people read digital images?</h1>' +
            '<p class="lead">Image-generation tools have made it easy to produce pictures that look ' +
            'photographic. We are collecting data on how people judge everyday images, and we would ' +
            'like your impressions.</p>' +

            '<ul class="factlist">' +
              '<li><span class="bullet">1</span><span>You will see a series of images one at a time and say ' +
              'whether you think each one is a real photograph or was generated by software.</span></li>' +
              '<li><span class="bullet">2</span><span>There are a few short blocks of images with brief ' +
              'question pages in between.</span></li>' +
              '<li><span class="bullet">3</span><span>It takes roughly 10&ndash;15 minutes. Please do it in ' +
              'one sitting, somewhere you can see the screen clearly.</span></li>' +
            '</ul>' +

            '<h3>Your data</h3>' +
            '<p class="muted">We record your answers, how long you took to answer, and the background ' +
            'questions you fill in. We do not collect your name, email address or anything else that ' +
            'identifies you. Your session is labelled with a random code. Participation is voluntary and ' +
            'you can close the tab at any point without giving a reason.</p>' +

            '<div class="notice">Please do not use image-search tools, AI assistants or other help. ' +
            'There are no right answers we expect from you &mdash; your honest first impression is exactly ' +
            'what is useful.</div>' +

            '<div class="btn-row">' +
              '<button class="btn btn--primary btn--lg" id="consent">I understand &mdash; start</button>' +
              '<span class="faint">By continuing you confirm you are 18 or older.</span>' +
            '</div>' +
          '</div>' +
        '</div>'
      );

      ui.on('#consent', 'click', function () {
        RAI.store.logEvent('consent_given');
        ctx.next();
      });
    }
  };
})(window);
